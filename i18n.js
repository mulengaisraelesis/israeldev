const SUPPORTED_LANGS = Object.keys(TRANSLATIONS);
const DEFAULT_LANG = "en";
const LANG_STORAGE_KEY = "israeldev.lang";

function readStoredLang() {
  try {
    return localStorage.getItem(LANG_STORAGE_KEY);
  } catch {
    return null;
  }
}

function storeLang(lang) {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    // Storage unavailable (private mode): language won't persist.
  }
}

function resolveInitialLang() {
  const candidates = [
    new URLSearchParams(window.location.search).get("lang"),
    readStoredLang(),
  ];
  return (
    candidates.find((lang) => SUPPORTED_LANGS.includes(lang)) ?? DEFAULT_LANG
  );
}

const i18n = {
  lang: resolveInitialLang(),

  t(key) {
    return (
      TRANSLATIONS[this.lang][key] ?? TRANSLATIONS[DEFAULT_LANG][key] ?? key
    );
  },

  apply(lang) {
    if (SUPPORTED_LANGS.includes(lang)) {
      this.lang = lang;
    }

    document.documentElement.lang = this.lang;
    document.title = this.t("meta.title");
    document
      .querySelector('meta[name="description"]')
      ?.setAttribute("content", this.t("meta.description"));

    document.querySelectorAll("[data-i18n]").forEach((node) => {
      node.textContent = this.t(node.dataset.i18n);
    });

    document.querySelectorAll("[data-i18n-html]").forEach((node) => {
      node.innerHTML = this.t(node.dataset.i18nHtml);
    });

    document.querySelectorAll("[data-i18n-attr]").forEach((node) => {
      node.dataset.i18nAttr.split(";").forEach((pair) => {
        const [attr, key] = pair.split(":").map((part) => part.trim());
        if (attr && key) {
          node.setAttribute(attr, this.t(key));
        }
      });
    });

    document.querySelectorAll("[data-lang-option]").forEach((node) => {
      const isActive = node.dataset.langOption === this.lang;
      node.classList.toggle("is-active", isActive);
      node.setAttribute("aria-pressed", String(isActive));
    });

    storeLang(this.lang);
  },
};

window.i18n = i18n;

document.querySelectorAll("[data-lang-option]").forEach((node) => {
  node.addEventListener("click", () => i18n.apply(node.dataset.langOption));
});

i18n.apply(i18n.lang);
